#!/usr/bin/env node
/**
 * Bundle packs/agent-orchestration/subagent/agents.ts plus the parseFrontmatter
 * dependency closure into a host-loadable ESM file.
 *
 * The packaged Electron app strips ordinary node_modules and extraResources
 * node_modules, so the catalog must not import extraResources agents.ts (which
 * bare-imports @earendil-works/pi-coding-agent). This script inlines the real
 * parser/discovery/apply module and only the frontmatter/yaml slice — never a
 * second AGENT.md schema parser.
 */
import { createRequire } from "node:module";
import { copyFileSync, existsSync, mkdirSync, readFileSync, statSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const packageRoot = join(here, "..");
const electronRoot = join(packageRoot, "../..");
const agentsEntry = join(electronRoot, "packs/agent-orchestration/subagent/agents.ts");
const subagentEntry = join(electronRoot, "packs/agent-orchestration/subagent/index.ts");
const srcOut = join(packageRoot, "src/runtime-agents.bundle.mjs");
const distOut = join(packageRoot, "dist/runtime-agents.bundle.mjs");
const scriptPath = fileURLToPath(import.meta.url);

const frontmatterJs = join(
  electronRoot,
  "node_modules/@earendil-works/pi-coding-agent/dist/utils/frontmatter.js",
);

function fail(message) {
  console.error(`[bundle-runtime-agents] ${message}`);
  process.exit(1);
}

function mtime(path) {
  return statSync(path).mtimeMs;
}

function isFresh(outfile, inputs) {
  if (!existsSync(outfile)) return false;
  const outTime = mtime(outfile);
  return inputs.every((input) => existsSync(input) && mtime(input) <= outTime);
}

const require = createRequire(import.meta.url);
let esbuild;
try {
  esbuild = require("esbuild");
} catch (error) {
  fail(`esbuild is required to bundle the catalog core: ${error instanceof Error ? error.message : String(error)}`);
}

if (!existsSync(agentsEntry)) fail(`missing source of truth: ${agentsEntry}`);
if (!existsSync(subagentEntry)) fail(`missing subagent extension entry: ${subagentEntry}`);
if (!existsSync(frontmatterJs)) fail(`missing parseFrontmatter implementation: ${frontmatterJs}`);

// The extension entry is shipped as TypeScript and parsed only when Pi starts.
// Parse it during every backend prebuild so packaging cannot successfully ship
// a runtime that immediately fails extension loading.
try {
  await esbuild.transform(readFileSync(subagentEntry, "utf8"), {
    loader: "ts",
    sourcefile: subagentEntry,
    target: "node22",
  });
} catch (error) {
  fail(`subagent extension entry does not parse: ${error instanceof Error ? error.message : String(error)}`);
}

const yamlRequire = createRequire(frontmatterJs);
let yamlBrowser;
try {
  const yamlPkg = dirname(yamlRequire.resolve("yaml/package.json"));
  yamlBrowser = join(yamlPkg, "browser/index.js");
} catch (error) {
  fail(`yaml (parseFrontmatter closure) is required: ${error instanceof Error ? error.message : String(error)}`);
}
if (!existsSync(yamlBrowser)) fail(`missing yaml browser entry: ${yamlBrowser}`);

const inputs = [agentsEntry, frontmatterJs, yamlBrowser, scriptPath];
const force = process.argv.includes("--force");
if (!force && isFresh(srcOut, inputs) && isFresh(distOut, inputs)) {
  process.exit(0);
}

const slimNamespace = "pi-coding-agent-slim";
const banner = `/**
 * Generated by packages/pi-backend/scripts/bundle-runtime-agents.mjs.
 * Source of truth: packs/agent-orchestration/subagent/agents.ts
 * plus @earendil-works/pi-coding-agent/dist/utils/frontmatter.js (yaml).
 * Do not edit. Host catalog must load this closure, never extraResources agents.ts.
 */
`;

const result = await esbuild.build({
  absWorkingDir: electronRoot,
  entryPoints: [agentsEntry],
  outfile: srcOut,
  bundle: true,
  platform: "node",
  format: "esm",
  target: "node22",
  legalComments: "none",
  logLevel: "warning",
  banner: { js: banner },
  plugins: [
    {
      name: slimNamespace,
      setup(build) {
        build.onResolve({ filter: /^@earendil-works\/pi-coding-agent$/ }, () => ({
          path: slimNamespace,
          namespace: slimNamespace,
        }));
        build.onResolve({ filter: /^yaml$/ }, () => ({ path: yamlBrowser }));
        build.onLoad({ filter: /.*/, namespace: slimNamespace }, () => ({
          contents: `
import { homedir } from "node:os";
import { join } from "node:path";
export { parseFrontmatter } from ${JSON.stringify(frontmatterJs)};
export const CONFIG_DIR_NAME = ".pi";
export function getAgentDir() {
  const envDir = process.env.PI_CODING_AGENT_DIR;
  if (typeof envDir === "string" && envDir.trim()) {
    const trimmed = envDir.trim();
    if (trimmed === "~") return homedir();
    if (trimmed.startsWith("~/") || trimmed.startsWith("~\\\\")) {
      return join(homedir(), trimmed.slice(2));
    }
    return trimmed;
  }
  return join(homedir(), ".pi", "agent");
}
`,
          resolveDir: dirname(frontmatterJs),
          loader: "js",
        }));
      },
    },
  ],
});

if (result.errors.length) {
  fail(result.errors.map((entry) => entry.text).join("\n"));
}

mkdirSync(dirname(distOut), { recursive: true });
copyFileSync(srcOut, distOut);

const bundled = readFileSync(srcOut, "utf8");
if (/from\s+["']@earendil-works\/pi-coding-agent["']/.test(bundled)) {
  fail("bundle still contains a bare @earendil-works/pi-coding-agent import");
}
if (!bundled.includes("yamlString") && !bundled.includes("parseFrontmatter")) {
  fail("bundle does not contain parseFrontmatter/yaml closure");
}
if (bundled.includes('Dynamic require of "') || /__require\("process"\)/.test(bundled)) {
  fail("bundle still uses a dynamic require that packaged-like Node cannot satisfy");
}
