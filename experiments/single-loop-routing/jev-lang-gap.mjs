// ---------------------------------------------------------------------------------------------------------------
// gate-3 state: a real kernel replay of the SL-13 fixture (fixtures/gate3-t2), positioned at commit_before.
// ---------------------------------------------------------------------------------------------------------------
async function gate3Reads() {
  const {turn: fixture} = readFixture('gate3-t2');
  const workspace = materialize('gate3-t2'), campaign = fixture.campaign;
  const gitDir = join(workspace, '.coc/repos', `${campaign}.git`), workTree = join(workspace, '.coc/campaigns', campaign);
  const reset = spawnSync('git', ['--git-dir', gitDir, '--work-tree', workTree, 'reset', '--hard', fixture.commit_before], {encoding: 'utf8'});
  if (reset.status !== 0) throw new Error(`git reset failed: ${reset.stderr}`);
  const kernel = startKernel({workspace, env: {}});
  try {
    await kernel.call('table.player_input', {campaign, text: fixture.player_input});
    const [capsule, applyOptions, resolveOptions] = await Promise.all([
      kernel.call('table.capsule', {campaign}), kernel.call('table.apply.options', {campaign}), kernel.call('table.resolve.options', {campaign})]);
    return {reads: {capsule, applyOptions, resolveOptions, located: []}, context: contextOf(capsule)};
  } finally { await kernel.close(); removeTree(workspace); }
}

function contextOf(capsule) {
  const where = capsule.where ?? {};
  return {scene: where.scene ?? '', clock: where.clock ?? null,
    present: (capsule.present ?? []).map(p => p.called?.name ?? p.name).filter(Boolean), receipts: []};
}

