/** Acceptance check (notes: "exact match on every id is the acceptance bar"): compare against the live telemetry. */
function verifyReconstruction(rows) {
  const want = {
    ask: ['obligation:globe-clippings-access', 'clue:globe-fire-cutoff', 'handout:Boston Globe City Desk Copy — Held from Print (1918)'],
    act: ['investigate', 'social', 'move', 'combat', 'flee', 'cast', 'idle', 'meta', 'stuck', 'ambiguous', 'montage'],
    item: ['笔记本', '开锁工具', '手电筒', '徽章'],
    addressee: ['Arty Wilmot', 'Ruth Blake'],
  };
  const problems = [];
  for (const [family, ids] of Object.entries(want)) {
    const got = (rows[family] ?? []).map(row => row.id);
    if (JSON.stringify(got) !== JSON.stringify(ids)) problems.push({family, want: ids, got});
  }
  return problems;
}

// ---------------------------------------------------------------------------------------------------------------
// Arms (see notes: a = as-is, b = translated input, c = play-language row labels where one exists, d = ask cut to 2).
// ---------------------------------------------------------------------------------------------------------------
function arms(rows) {
  const base = structuredClone(rows);
  const d = structuredClone(rows);
  d.ask = d.ask.slice(0, 1); // obligation only (+ none, added automatically by askedFamilies/compileBatch)
  return {
    a: {rawInput: SENTENCE_ZH, rows: base, label: 'as-is (zh input, kernel rows)'},
    b: {rawInput: SENTENCE_EN, rows: structuredClone(rows), label: 'translated input (en), same rows'},
    // c: addressee is already Chinese-labelled in (a) (see notes); ask has no play-language label to swap in --
    // left byte-identical to (a) by design, not by omission.
    c: {rawInput: SENTENCE_ZH, rows: structuredClone(rows), label: 'play-language row labels where one exists (identical to a for ask+addressee; see notes)'},
    d: {rawInput: SENTENCE_ZH, rows: d, label: 'ask cut to obligation + none only'},
  };
}

async function runArm(decision, scope, readSet, stateLabel, armKey, arm, context) {
  const view = {runId: `jev-lang-gap-${stateLabel}-${armKey}`, rawInput: arm.rawInput,
    context, materials: [], candidates: [], rows: arm.rows, observations: []};
  const results = [];
  for (let i = 0; i < RUNS; i++) {
    const batch = compileBatch({...view, runId: `${view.runId}-run${i + 1}`, observations: [{n: i}]}, scope, readSet, []);
    const lease = new TaskLease({owner: 'single-loop-compile', goal: arm.rawInput, scope, capabilities: ['decision'], readSet,
      budget: {deadlineAt: Date.now() + 20_000, remainingInputTokens: 400_000, remainingOutputTokens: 40_000, remainingCostUsd: 2, remainingActions: 60}});
    let result;
    try { result = await decision.decide(batch, lease); } finally { lease.close(); }
    const ask = answerOf(result, 'ask'), addressee = answerOf(result, 'addressee');
    results.push({
      run: i + 1, status: result.status, failure: result.failure ?? null,
      ask: {...ask, cleared: ask.choice ? clears(result, 'ask', ask.choice, ask.confidence, GATE) : false},
      addressee: {...addressee, cleared: addressee.choice ? clears(result, 'addressee', addressee.choice, addressee.confidence, GATE) : false},
    });
  }
  return results;
}

function summarize(results, rows) {
  const obligationAlias = (rows.ask ?? []).length ? 'ask_1' : null; // obligation is always ask_1 in every arm here
  const arty = 'addressee_1'; // Arty Wilmot is always addressee_1 in the rows built above
  const obligationProbs = results.map(r => r.ask.probabilities?.[obligationAlias] ?? (r.ask.choice === obligationAlias ? 1 : 0)).filter(v => v !== undefined);
  const artyProbs = results.map(r => r.addressee.probabilities?.[arty]).filter(v => v !== undefined);
  const mean = values => values.length ? values.reduce((a, b) => a + b, 0) / values.length : null;
  const spread = values => values.length ? Math.max(...values) - Math.min(...values) : null;
  const clearedCount = (family, alias) => results.filter(r => r[family].choice === alias && r[family].cleared).length;
  return {
    n: results.length,
    obligation: {mean: mean(obligationProbs), spread: spread(obligationProbs), values: obligationProbs, cleared_at_gate: clearedCount('ask', obligationAlias)},
    addressee_arty: {mean: mean(artyProbs), spread: spread(artyProbs), values: artyProbs, cleared_at_gate: clearedCount('addressee', arty)},
  };
}

async function main() {
  console.log('gate-3: materializing fixture, positioning at commit_before, opening turn 2...');
  const gate3 = await gate3Reads();
  console.log('gate-4: reconstructing StateReads from telemetry + module content...');
  const gate4 = gate4Reads();

  const gate3Rows = compileRows(gate3.reads), gate4Rows = compileRows(gate4.reads);
  const gate4Problems = verifyReconstruction(gate4Rows);
  console.log('gate-4 reconstruction id-match check:', gate4Problems.length ? JSON.stringify(gate4Problems) : 'OK (ask/act/item/addressee ids match live telemetry exactly)');
  console.log('gate-3 families asked:', askedFamilies(gate3Rows), 'gate-4 families asked:', askedFamilies(gate4Rows));

  const decision = createDecisionAdapter({env, maxConcurrency: 1});
  const scope = {owner: 'campaign:jev-lang-gap', campaign: 'jev-lang-gap', worldline: 'main', loop: 0, audience: 'keeper'};
  const readSet = [{kind: 'model', resource: 'decision', revision: JEV_MODEL}, {kind: 'family', resource: 'single-loop-compile', revision: '1'}];

  const out = {generated_at: new Date().toISOString(), runs_per_arm: RUNS, gate4_reconstruction_problems: gate4Problems, states: {}};
  for (const [stateLabel, rows, context] of [['gate3', gate3Rows, gate3.context], ['gate4', gate4Rows, gate4.context]]) {
    out.states[stateLabel] = {};
    const theArms = arms(rows);
    for (const [armKey, arm] of Object.entries(theArms)) {
      console.log(`--- ${stateLabel} / arm ${armKey}: ${arm.label} ---`);
      const results = await runArm(decision, scope, readSet, stateLabel, armKey, arm, context);
      const summary = summarize(results, arm.rows);
      console.log(JSON.stringify(summary));
      out.states[stateLabel][armKey] = {label: arm.label, results, summary};
      writeFileSync(join(OUT, `${stateLabel}-${armKey}.json`), JSON.stringify({label: arm.label, rows: arm.rows, results, summary}, null, 1) + '\n');
    }
  }
  writeFileSync(join(OUT, 'all.json'), JSON.stringify(out, null, 1) + '\n');
  console.log('done ->', OUT);
}

await main();
